// Guest SDK for paglets (paglet ABI v1, planning/cpp-abi-v1.md), compiled to
// wasm32-wasip1 by clang.
//
// A paglet derives from paglets::Paglet, registers message handlers on its
// router and is made known to the SDK with PAGLETS_PAGLET(Type):
//
//     struct Hello : paglets::Paglet {
//         Hello() {
//             router().on("greet", [](paglets::Message& m) {
//                 m.reply(std::string("hello"));
//             });
//         }
//     };
//     PAGLETS_PAGLET(Hello)
//
// The paglet object and everything it owns live in linear memory, so memory
// images move them without serialization code. Message bodies are encoded
// with paglets::msgpack; types generated by schema_gen plug in through
// paglets_encode / paglets_decode.

