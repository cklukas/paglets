using Bytes = std::vector<std::uint8_t>;

// Results carry an ABI error code (abi::Error) on failure.
template <class T>
using Result = std::expected<T, std::int32_t>;

template <class T>
Bytes encode(const T& value) {
    msgpack::Writer w;
    msgpack::write_value(w, value);
    return w.take();
}

template <class T>
bool decode(std::span<const std::uint8_t> bytes, T& value) {
    msgpack::Reader r(bytes);
    return msgpack::read_value(r, value) && r.ok() && r.at_end();
}

