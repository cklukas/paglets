// Patterns: zombie paglets (docs/zombie-paglets.md, docs/zombie-protocol.md).
// A paglet derived from Zombie<Work> keeps running as long as one host of
// its mesh is alive. The creator calls start_group(): the paglet clones
// itself to every other host of the mesh, one replica per host. One
// replica, the main, works: the base class calls step() while it is the
// acting main. The others sleep and take over from the latest checkpoint
// when the main disappears. When step() reports the work done, result()
// goes to the group's sink, exactly one result counts, and every replica
// ends.
//
// The protocol is the specification's state machine
// (paglets/protocols/zombie/zombie.hpp); this class carries out its
// outputs: messages between the replicas, timers, checkpoints of the memory
// image (a step that outputs Persist sends its messages only from the next
// handler, after the image is stored), the host's `zombies` registry
// (joining, tombstones, the sink, traces), and the work.
//
// Work is the paglet's job state, encoded with paglets_encode/decode (types
// generated by schema_gen have them). Observations made with observe() go
// to the journal, which every replica merges and the result can use.
//
// Modules using it list the services `zombies`, `mesh_info` and `user_info`.

